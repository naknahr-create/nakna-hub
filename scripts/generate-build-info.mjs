import {execFileSync} from 'node:child_process';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

// Runs before every local dev session and every Cloudflare Workers build.
// The generated module is bundled into both the UI and the version endpoint.
const root=fileURLToPath(new URL('../',import.meta.url));
const pkg=JSON.parse(await readFile(new URL('../package.json',import.meta.url),'utf8'));
let commit='';
try {
  commit=execFileSync('git',['rev-parse','--verify','HEAD'],{
    cwd:root,encoding:'utf8',timeout:4000,stdio:['ignore','pipe','ignore']
  }).trim();
} catch { /* Build archives may not contain .git. */ }
if(!/^[a-f0-9]{40}$/i.test(commit)){
  commit=[process.env.CF_PAGES_COMMIT_SHA,process.env.GITHUB_SHA,process.env.COMMIT_SHA]
    .find(value=>typeof value==='string'&&/^[a-f0-9]{40}$/i.test(value))||'';
}
const builtAt=new Date().toISOString();
const buildId=`${commit?commit.slice(0,12):'build'}-${builtAt.replace(/\D/g,'').slice(0,14)}`;
const info={version:String(pkg.version||'0.0.0'),commit,buildId,builtAt};
const output='// Generated by scripts/generate-build-info.mjs. Do not edit.\n'
  +`export const BUILD_INFO = ${JSON.stringify(info,null,2)} as const;\n`;
await writeFile(new URL('../lib/build-info.generated.ts',import.meta.url),output,'utf8');
console.log(`HUB build: v${info.version} · ${commit?commit.slice(0,8):buildId} · ${builtAt}`);
